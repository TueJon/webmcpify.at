/**
 * Generate .well-known/webmcp.json from the tools the site actually registers.
 *
 *     node build-manifest.mjs
 *
 * The manifest is a mirror for pre-visit discovery, never a source: the imperative
 * entries come straight from webmcp/tools.js, and the declarative entry mirrors the
 * install form in index.html (tests/agent-discovery.test.mjs asserts that pairing).
 * Run after changing any tool contract and commit the result.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TOOLS } from './webmcp/tools.js';

const root = dirname(fileURLToPath(import.meta.url));
const OUT = join(root, '.well-known', 'webmcp.json');

// Registered by the browser from <form id="install-picker">, so it has no runtime
// object to read: keep in step with the form's attributes and options.
const DECLARATIVE = [
  {
    name: 'show_install_command',
    description:
      'Switches the install command shown in the Installation section to the variant for a given agent setup. Page-local display change; use get_install_command for the raw text.',
    inputSchema: {
      type: 'object',
      properties: {
        agent: {
          type: 'string',
          enum: ['npx', 'plugin', 'git'],
          description:
            'Install route to display: npx (skills CLI, works with any agent), plugin (Claude Code plugin marketplace), git (manual clone)',
        },
      },
      required: ['agent'],
      additionalProperties: false,
    },
    annotations: { readOnlyHint: false },
    declarative: true,
  },
];

export function buildManifest() {
  const manifest = {
    $comment:
      'Pre-visit discovery manifest, generated by build-manifest.mjs. The WebMCP spec (W3C Web Machine Learning CG) defines no manifest format; this follows the de-facto shape third-party crawlers and inspectors probe at /.well-known/webmcp. It mirrors the tools this site registers at runtime — the runtime registration is authoritative.',
    name: 'webmcpify',
    description:
      "Project site for webmcpify, an MIT-licensed agent skill that makes an existing web app agent-ready with WebMCP: inventory the app's user actions, approve a tool manifest, integrate, verify every tool in a real browser, heal, audit.",
    version: '1.0.0',
    homepage: 'https://webmcpify.at/',
    documentation: 'https://webmcpify.at/llms.txt',
    source: 'https://github.com/TueJon/webmcpify',
    spec: 'https://webmachinelearning.github.io/webmcp/',
    tools: [
      ...TOOLS.map(({ name, description, inputSchema, annotations }) => ({
        name,
        description,
        inputSchema,
        annotations,
      })),
      ...DECLARATIVE,
    ],
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const json = buildManifest();
  writeFileSync(OUT, json, 'utf8');
  console.log(`wrote ${OUT} (${json.length} bytes)`);
}
